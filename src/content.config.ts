// Content collections. The study and post schemas mirror the NeuroPulse record standard
// (NeuroPulse-Co/.github/standards/RECORDS.md and tools/record.py). A showcase file that
// breaks the standard fails the build here, with the file and field named.
import { defineCollection, z } from "astro:content";
import { glob } from "astro/loaders";

const STATUSES = [
  "planned",
  "running",
  "closed-positive",
  "closed-negative",
  "closed-inconclusive",
  "abandoned",
] as const;

const keyResult = z.object({
  label: z.string(),
  value: z.number(),
  unit: z.string(),
  split: z.enum(["val", "test", "none"]),
  n_seeds: z.number().int().min(1),
  std: z.number().optional(),
  ci95: z.tuple([z.number(), z.number()]).optional(),
  compare: z.object({ label: z.string(), value: z.number() }).optional(),
});

const workstreamId = z.string().regex(/^W\d+$/);

// showcase/<repo>/studies/<id>.md, generated by `record.py promote`.
const studies = defineCollection({
  loader: glob({
    pattern: "*/studies/*.md",
    base: "./src/content/showcase",
    generateId: ({ entry }) => entry.replace(/\.md$/, ""),
  }),
  schema: z.object({
    id: z.string().regex(/^[a-z0-9][a-z0-9-]*$/),
    repo: z.string(),
    title: z.string(),
    workstream: workstreamId,
    status: z.enum(STATUSES),
    owner: z.array(z.string()).min(1),
    started: z.coerce.date(),
    closed: z.coerce.date().optional(),
    summary: z.string(),
    question: z.string(),
    hypothesis: z.string(),
    success_criterion: z.string(),
    criterion: z.enum(["pre_registered", "post_hoc"]),
    verdict: z.string().optional(),
    key_results: z.array(keyResult).optional(),
    code_url: z.string().url(),
  }),
});

// Milestone posts: from research repos (showcase/<repo>/posts/) and site-owned (src/content/posts/).
const posts = defineCollection({
  loader: glob({
    pattern: ["showcase/*/posts/*.md", "posts/*.md"],
    base: "./src/content",
    generateId: ({ entry }) =>
      entry.replace(/^showcase\/[^/]+\/posts\//, "").replace(/^posts\//, "").replace(/\.md$/, ""),
  }),
  schema: z.object({
    title: z.string(),
    date: z.coerce.date(),
    authors: z.array(z.string()).min(1),
    workstream: workstreamId,
    summary: z.string(),
    study: z.string().optional(),
    cover: z.string().optional(),
    draft: z.boolean().default(false),
  }),
});

// Site-owned plain-language explainer for each workstream (src/content/workstreams/W*.md).
const workstreams = defineCollection({
  loader: glob({ pattern: "W*.md", base: "./src/content/workstreams" }),
  schema: z.object({
    id: workstreamId,
    title: z.string(),
    tagline: z.string(),
  }),
});

export const collections = { studies, posts, workstreams };
